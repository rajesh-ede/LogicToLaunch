class Student{
    String name;
    String department;
    int passedOutYear;
    int score;
    double fee;
    Student(String name,String department,int passedOutYear,int score,double fee){
        this.name = name;
        this.department = department;
        this.passedOutYear = passedOutYear;
        this.score = score;
        this.fee = fee;
    }
}